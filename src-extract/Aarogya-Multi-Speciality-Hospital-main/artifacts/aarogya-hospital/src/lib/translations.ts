// Clock time for display. Minutes are counted from midnight.
function enTime(minutes: number) {
  const h = Math.floor(minutes / 60);
  const m = minutes % 60;
  const hour12 = ((h + 11) % 12) + 1;
  return `${hour12}:${String(m).padStart(2, '0')} ${h < 12 ? 'AM' : 'PM'}`;
}

function teTime(minutes: number) {
  const h = Math.floor(minutes / 60);
  const m = minutes % 60;
  const hour12 = ((h + 11) % 12) + 1;
  const period = h < 12 ? 'ఉదయం' : h < 16 ? 'మధ్యాహ్నం' : h < 19 ? 'సాయంత్రం' : 'రాత్రి';
  return `${period} ${hour12}:${String(m).padStart(2, '0')}`;
}

